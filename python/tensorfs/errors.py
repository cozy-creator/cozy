"""Typed refusals.

Every refusal code in the compiled core has exactly one exception class here, and the set
is BUILT IN RUST from `err::Code::ALL` — the names below are the frozen Python spelling of
it, re-exported one at a time so a type checker can see them. It used to be one
`__getattr__`, which meant `except errors.SortOder` type-checked and then raised
`AttributeError` at the moment the refusal it was written to catch arrived (tfs-077).
`scripts/stub_conform.py` holds this list against the extension.

Catch one (`except errors.ShortRead`) or the family::

    try:
        lease.read_into(oid, length, off, n, buf)
    except errors.Refusal as e:
        log(e.code, e.detail)      # "SHORT_READ", "...is 512 B on disk, the reference..."

`CODES` maps the frozen wire name to its class for callers that dispatch on the wire name
rather than on the type.
"""

